/** Builds data/seed.sql from an Overpass export (data/osm-raw.json). Licence: ODbL, © OpenStreetMap contributors.
 *  Usage: npx tsx scripts/seed-osm.ts  (then: npx wrangler d1 execute windext --file data/seed.sql [--remote]) */
import { readFileSync, writeFileSync } from 'node:fs'
import { slugify, distanceKm } from '../src/core/store.js'

export interface SeedRow { id: string; name: string; aliases: string[]; lat: number; lon: number; country: string; sports: string[]; kind: 'spot' | 'school'; launch_notes: string; source: string }

const SPORT_MAP: Record<string, string> = { kitesurfing: 'kitesurf', kiteboarding: 'kitesurf', windsurfing: 'windsurf', wingfoil: 'wingfoil', wing_foil: 'wingfoil', wingsurfing: 'wingfoil', sailing: 'sailing' }
const SCHOOL_KEYS: [string, RegExp][] = [['amenity', /school|training/], ['shop', /.*/], ['leisure', /sports_centre|fitness_centre/], ['club', /.*/], ['tourism', /hotel|guest_house|camp_site|hostel/], ['office', /.*/], ['craft', /.*/]]

export function classify(tags: Record<string, string>): 'spot' | 'school' {
  for (const [k, re] of SCHOOL_KEYS) if (tags[k] && re.test(tags[k])) return 'school'
  if (/club|school|shop|center|centre|verein|e\.v\.|hostel|hotel|camping/i.test(tags.name ?? '')) return 'school'
  return 'spot'
}

export function toRows(elements: any[]): SeedRow[] {
  const rows: SeedRow[] = []
  for (const e of elements) {
    const t: Record<string, string> = e.tags ?? {}
    const lat = e.lat ?? e.center?.lat, lon = e.lon ?? e.center?.lon
    if (lat == null || lon == null) continue
    const sports = Array.from(new Set((t.sport ?? '').split(';').map(s => SPORT_MAP[s.trim()]).filter(Boolean)))
    if (!sports.length) continue
    const name = (t['name:en'] ?? t.name ?? '').trim()
    const kind = classify(t)
    const baseName = name || `Unnamed ${sports[0]} ${kind} (OSM ${e.type} ${e.id})`
    const aliases = Object.entries(t).filter(([k]) => k.startsWith('name:') || k === 'alt_name' || k === 'old_name').map(([, v]) => v.toLowerCase())
    const notes = [t.description, t.note, t.website ? `web: ${t.website}` : ''].filter(Boolean).join(' | ').slice(0, 500)
    rows.push({ id: name ? `${slugify(name)}-osm-${e.id}` : `osm-${e.type}-${e.id}`, name: baseName, aliases: Array.from(new Set(aliases)), lat: +lat.toFixed(5), lon: +lon.toFixed(5), country: t['addr:country'] ?? '', sports, kind, launch_notes: notes, source: `https://www.openstreetmap.org/${e.type}/${e.id}` })
  }
  // Dedupe: two objects within 300 m with the same kind -> keep the one with the richer tags (longer notes/aliases), merge sports.
  const kept: SeedRow[] = []
  for (const r of rows.sort((a, b) => (b.launch_notes.length + b.aliases.length) - (a.launch_notes.length + a.aliases.length))) {
    const dup = kept.find(k => k.kind === r.kind && distanceKm(k, r) < 0.3)
    if (dup) { dup.sports = Array.from(new Set([...dup.sports, ...r.sports])); dup.aliases = Array.from(new Set([...dup.aliases, r.name.toLowerCase()])); continue }
    kept.push(r)
  }
  return kept.sort((a, b) => a.id.localeCompare(b.id))
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`
export function toSql(rows: SeedRow[]): string {
  const lines = ['-- Generated by scripts/seed-osm.ts. Data © OpenStreetMap contributors, ODbL.']
  for (const r of rows) {
    lines.push(`INSERT OR IGNORE INTO spots (id, name, aliases, lat, lon, country, sports, kind, launch_notes, status, facing_source, sources, submissions) VALUES (${q(r.id)}, ${q(r.name)}, ${q(r.aliases.join('|'))}, ${r.lat}, ${r.lon}, ${q(r.country)}, ${q(r.sports.join('|'))}, ${q(r.kind)}, ${q(r.launch_notes)}, 'seed', 'seed', ${q(r.source)}, 0);`)
  }
  return lines.join('\n') + '\n'
}

if (process.argv[1]?.endsWith('seed-osm.ts')) {
  const raw = JSON.parse(readFileSync('data/osm-raw.json', 'utf8'))
  const rows = toRows(raw.elements)
  writeFileSync('data/seed.sql', toSql(rows))
  const spots = rows.filter(r => r.kind === 'spot').length
  console.log(`${rows.length} rows (${spots} spots, ${rows.length - spots} schools/clubs/shops) -> data/seed.sql`)
}
