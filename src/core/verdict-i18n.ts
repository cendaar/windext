const fill = (tpl: string, vars: Record<string, string | number>, lang: Lang) =>
  tpl.replace(/\{(\w+)\}/g, (_, k) => {
    const v = vars[k]
    if (v == null || v === '') return ''
    if (k === 'dir') return COMPASS_NAMES[lang][String(v)] ?? String(v)
    if (typeof v === 'number' && lang !== 'en') return String(v).replace('.', ',')
    return String(v)
  })

export interface RenderedDay { day: string; date: string; status: DayVerdict['status']; headline: string; reasons: string[]; window: DayVerdict['window']; gear: DayVerdict['gear']; wind: DayVerdict['wind']; confidence: DayVerdict['confidence']; score: number; codes: string[] }

export function renderVerdict(v: DayVerdict, lang: Lang): RenderedDay {
  const T = VERDICT_TEXT[lang]
  const head = v.headline.code === 'CHECK' && v.window ? 'CHECK_W' : v.headline.code
  return {
    day: v.day === 'today' ? T.TODAY : T.TOMORROW, date: v.date, status: v.status,
    headline: fill(T[head], v.headline.vars, lang),
    reasons: v.reasons.map(r => fill(T[r.code], r.vars, lang)),
    window: v.window, gear: v.gear, wind: v.wind, confidence: v.confidence, score: v.score, codes: v.codes,
  }
}
